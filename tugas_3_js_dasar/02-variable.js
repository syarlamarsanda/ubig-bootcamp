/* VARIABLE: Variable diibaratkan seperti wadah makanan yang diberi label,
agar jika disi dengan berbagai komponen makanan, dan mau milih makananya, tinggal dipanggil nama labelnya*/

let nama = "syarla marsanda"; //LET itu jenis kotaknya, NAMA itu labelnya
console.log(nama);  // let isinya bisa diganti tapi kalo double let bakal langsung error

const sekolah = "SMKS Cyber media"; //isinya gabisa diganti ditengah jalan
console.log(sekolah);

var kelas = "10"; //isinya bisa diganti, dan bisa diduplikat berkali kali tanpa error
var kelas = "11";
console.log(kelas);

